"use client";

import React, { useState, useEffect } from "react";
import { useRouter } from "next/navigation";
import { useAuth } from "@/context/AuthContext";
import { Project, Task } from "@/types/database";
import { DatabaseService } from "@/lib/supabase/service";
import { Sidebar } from "@/components/dashboard/Sidebar";
import { Header } from "@/components/dashboard/Header";
import { ProjectStats } from "@/components/dashboard/ProjectStats";
import { ProjectCard } from "@/components/dashboard/ProjectCard";
import { TaskList } from "@/components/dashboard/TaskList";
import { DatabaseView } from "@/components/dashboard/DatabaseView";
import { CopilotDrawer } from "@/components/dashboard/CopilotDrawer";
import { CreateProjectModal } from "@/components/dashboard/CreateProjectModal";
import { EditProjectModal } from "@/components/dashboard/EditProjectModal";
import { DeleteConfirmModal } from "@/components/dashboard/DeleteConfirmModal";
import { CreateTaskModal } from "@/components/dashboard/CreateTaskModal";
import { Button } from "@/components/ui/Button";
import { Plus, Sparkles, FolderPlus, ArrowLeft } from "lucide-react";

export default function DashboardPage() {
  const router = useRouter();
  const { user, isLoading: authLoading } = useAuth();

  const [activeView, setActiveView] = useState<"projects" | "tasks" | "copilot" | "database">("projects");
  const [mobileSidebarOpen, setMobileSidebarOpen] = useState(false);
  const [searchQuery, setSearchQuery] = useState("");
  const [activeFilter, setActiveFilter] = useState("all");

  const [projects, setProjects] = useState<Project[]>([]);
  const [tasks, setTasks] = useState<Task[]>([]);
  const [loadingData, setLoadingData] = useState(true);

  // Selected project context
  const [selectedProjectId, setSelectedProjectId] = useState<string | null>(null);

  // Modals state
  const [createProjectOpen, setCreateProjectOpen] = useState(false);
  const [editProject, setEditProject] = useState<Project | null>(null);
  const [deleteProject, setDeleteProject] = useState<Project | null>(null);
  const [createTaskOpen, setCreateTaskOpen] = useState(false);
  const [createTaskProjectId, setCreateTaskProjectId] = useState<string | undefined>(undefined);
  const [copilotOpen, setCopilotOpen] = useState(false);

  // Load projects and tasks on mount or user change
  useEffect(() => {
    async function fetchData() {
      setLoadingData(true);
      try {
        const uId = user?.id || "00000000-0000-0000-0000-000000000001";
        const [loadedProjects, loadedTasks] = await Promise.all([
          DatabaseService.getProjects(uId),
          DatabaseService.getTasks(undefined, uId),
        ]);
        setProjects(loadedProjects);
        setTasks(loadedTasks);
      } finally {
        setLoadingData(false);
      }
    }

    if (!authLoading) {
      fetchData();
    }
  }, [user, authLoading]);

  // Project CRUD handlers
  const handleProjectCreated = (newProj: Project) => {
    setProjects((prev) => [newProj, ...prev]);
  };

  const handleProjectUpdated = (updatedProj: Project) => {
    setProjects((prev) =>
      prev.map((p) => (p.id === updatedProj.id ? updatedProj : p))
    );
  };

  const handleProjectDeleted = (deletedId: string) => {
    setProjects((prev) => prev.filter((p) => p.id !== deletedId));
    setTasks((prev) => prev.filter((t) => t.project_id !== deletedId));
    if (selectedProjectId === deletedId) {
      setSelectedProjectId(null);
    }
  };

  // Task CRUD handlers
  const handleTaskCreated = (newTask: Task) => {
    setTasks((prev) => [newTask, ...prev]);
  };

  const handleToggleTaskStatus = async (task: Task) => {
    const nextStatus = task.status === "completed" ? "pending" : "completed";
    // Optimistic UI update
    setTasks((prev) =>
      prev.map((t) => (t.id === task.id ? { ...t, status: nextStatus } : t))
    );

    await DatabaseService.updateTask(
      task.id,
      { status: nextStatus },
      user?.id || task.user_id
    );
  };

  const handleDeleteTask = async (taskId: string) => {
    setTasks((prev) => prev.filter((t) => t.id !== taskId));
    await DatabaseService.deleteTask(taskId, user?.id || "00000000-0000-0000-0000-000000000001");
  };

  const handleAddTaskFromCopilot = async (
    targetProjectId: string,
    taskTitle: string,
    priority: "high" | "medium" | "low"
  ) => {
    const newTask = await DatabaseService.createTask({
      project_id: targetProjectId,
      user_id: user?.id || "00000000-0000-0000-0000-000000000001",
      title: taskTitle,
      description: "Generated by LaunchPilot Intelligent AI Copilot",
      status: "pending",
      priority,
      due_date: new Date(Date.now() + 3 * 86400000).toISOString(),
    });
    handleTaskCreated(newTask);
  };

  // Filtered projects
  const filteredProjects = projects.filter((p) => {
    if (activeFilter !== "all" && p.status !== activeFilter) return false;
    if (searchQuery.trim()) {
      const q = searchQuery.toLowerCase();
      const matchTitle = p.title.toLowerCase().includes(q);
      const matchDesc = p.description?.toLowerCase().includes(q);
      return matchTitle || matchDesc;
    }
    return true;
  });

  const selectedProject = projects.find((p) => p.id === selectedProjectId);
  const completedTaskCount = tasks.filter((t) => t.status === "completed").length;

  return (
    <div className="flex min-h-screen bg-slate-50 dark:bg-slate-950 transition-colors">
      {/* Sidebar navigation */}
      <Sidebar
        activeView={activeView}
        onSelectView={(v) => {
          setActiveView(v);
          if (v === "copilot") {
            setCopilotOpen(true);
          }
        }}
        isOpenMobile={mobileSidebarOpen}
        onCloseMobile={() => setMobileSidebarOpen(false)}
        projectCount={projects.length}
        taskCount={tasks.length}
      />

      {/* Main Content Area */}
      <div className="flex-1 flex flex-col min-w-0">
        <Header
          onOpenMobileSidebar={() => setMobileSidebarOpen(true)}
          onOpenCreateProject={() => setCreateProjectOpen(true)}
          onOpenCopilot={() => setCopilotOpen(true)}
          searchQuery={searchQuery}
          onSearchChange={setSearchQuery}
        />

        <main className="flex-1 p-4 sm:p-6 lg:p-8 max-w-7xl w-full mx-auto">
          {/* Breadcrumb if project is selected */}
          {selectedProjectId && (
            <div className="mb-4 flex items-center gap-2">
              <Button
                variant="ghost"
                size="sm"
                onClick={() => setSelectedProjectId(null)}
                leftIcon={<ArrowLeft className="w-3.5 h-3.5" />}
                className="text-xs"
              >
                Back to All Projects
              </Button>
              <span className="text-slate-300 dark:text-slate-700">/</span>
              <span className="text-xs font-bold text-slate-700 dark:text-slate-300">
                {selectedProject?.title}
              </span>
            </div>
          )}

          {/* View 1: Projects Overview */}
          {activeView === "projects" && !selectedProjectId && (
            <div>
              <ProjectStats
                totalProjects={projects.length}
                totalTasks={tasks.length}
                completedTasks={completedTaskCount}
                activeFilter={activeFilter}
                onFilterChange={setActiveFilter}
              />

              {loadingData ? (
                <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-5">
                  {[1, 2, 3].map((i) => (
                    <div
                      key={i}
                      className="h-44 rounded-2xl bg-slate-200/60 dark:bg-slate-850/60 animate-pulse border border-slate-200 dark:border-slate-800"
                    />
                  ))}
                </div>
              ) : filteredProjects.length === 0 ? (
                <div className="p-12 text-center rounded-3xl border border-dashed border-slate-200 dark:border-slate-800 bg-white/50 dark:bg-slate-900/40">
                  <FolderPlus className="w-10 h-10 text-slate-400 mx-auto mb-3" />
                  <h3 className="text-base font-bold text-slate-900 dark:text-white">
                    No initiatives found
                  </h3>
                  <p className="text-xs text-slate-500 dark:text-slate-400 mt-1 max-w-sm mx-auto">
                    {searchQuery
                      ? "No projects match your search query."
                      : "Create your first project to start tracking deliverables with AI."}
                  </p>
                  <Button
                    size="sm"
                    variant="primary"
                    onClick={() => setCreateProjectOpen(true)}
                    className="mt-4"
                    leftIcon={<Plus className="w-4 h-4" />}
                  >
                    Create Project
                  </Button>
                </div>
              ) : (
                <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-5">
                  {filteredProjects.map((project) => (
                    <ProjectCard
                      key={project.id}
                      project={project}
                      tasks={tasks}
                      onSelect={(p) => setSelectedProjectId(p.id)}
                      onEdit={(p) => setEditProject(p)}
                      onDelete={(p) => setDeleteProject(p)}
                      onOpenCopilot={(p) => {
                        setSelectedProjectId(p.id);
                        setCopilotOpen(true);
                      }}
                    />
                  ))}
                </div>
              )}
            </div>
          )}

          {/* View 2: Selected Project Task Matrix */}
          {(selectedProjectId || activeView === "tasks") && (
            <div className="bg-white/80 dark:bg-slate-900/60 border border-slate-200/80 dark:border-slate-800 rounded-3xl p-6 shadow-sm backdrop-blur-sm">
              <TaskList
                tasks={tasks}
                projects={projects}
                selectedProjectId={selectedProjectId}
                onToggleStatus={handleToggleTaskStatus}
                onDeleteTask={handleDeleteTask}
                onOpenCreateTask={(pId) => {
                  setCreateTaskProjectId(pId || selectedProjectId || undefined);
                  setCreateTaskOpen(true);
                }}
              />
            </div>
          )}

          {/* View 3: Database & Security Info */}
          {activeView === "database" && <DatabaseView />}
        </main>
      </div>

      {/* Copilot Drawer */}
      <CopilotDrawer
        isOpen={copilotOpen}
        onClose={() => setCopilotOpen(false)}
        projects={projects}
        selectedProject={selectedProject}
        onAddTaskFromCopilot={handleAddTaskFromCopilot}
      />

      {/* Modals */}
      <CreateProjectModal
        isOpen={createProjectOpen}
        onClose={() => setCreateProjectOpen(false)}
        onProjectCreated={handleProjectCreated}
      />

      <EditProjectModal
        isOpen={Boolean(editProject)}
        project={editProject}
        onClose={() => setEditProject(null)}
        onProjectUpdated={handleProjectUpdated}
      />

      <DeleteConfirmModal
        isOpen={Boolean(deleteProject)}
        project={deleteProject}
        onClose={() => setDeleteProject(null)}
        onProjectDeleted={handleProjectDeleted}
      />

      <CreateTaskModal
        isOpen={createTaskOpen}
        onClose={() => setCreateTaskOpen(false)}
        projects={projects}
        defaultProjectId={createTaskProjectId}
        onTaskCreated={handleTaskCreated}
      />
    </div>
  );
}
